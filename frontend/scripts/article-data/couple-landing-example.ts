import { writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { buildCoupleTimelineV3 } from '../../../backend/src/lib/report/timelineV3/couple.js'

// Fictional inputs from SEO-06; Japan standard time follows the web guest policy.
export function buildCoupleLandingExample() {
  const timeline = buildCoupleTimelineV3({
    self: { birthDate: '1995-02-20', gender: 'female', birthTimeZone: 'Asia/Tokyo' },
    partner: { birthDate: '1992-07-15', gender: 'male', birthTimeZone: 'Asia/Tokyo' },
    relationshipLabel: 'お付き合い中', meetingYear: 2021, referenceYear: 2026, endYear: 2026,
  })
  if (timeline.status !== 'ready') throw new Error('Couple example calculation failed')
  return {
    engineVersion: timeline.engineVersion, referenceYear: timeline.referenceYear,
    rows: [2021, 2023, 2025].map(year => {
      const card = timeline.entries.find(entry => entry.year === year)?.card
      if (!card) throw new Error('Missing couple example year')
      const body = card.sections?.[0]?.body
      if (!body) throw new Error('Missing couple example text')
      return { year, title: card.title, tags: (card.tags ?? []).filter(tag => tag.startsWith('#')),
        excerpt: body.split('。').filter(Boolean).slice(0, 2).join('。') + '。' }
    }),
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const example = buildCoupleLandingExample()
  writeFileSync(new URL('../../src/web/data/coupleLandingExample.js', import.meta.url),
    '// Generated by scripts/article-data/couple-landing-example.ts; fictional inputs only.\n' +
    `export const coupleLandingExample = ${JSON.stringify(example, null, 2)}\n`)
  console.log(`Verified example from ${example.engineVersion}: ${example.rows.length} years`)
}

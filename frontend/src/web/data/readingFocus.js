export const readingFocusPaths = Object.values(readingFocusPages).map(page => page.path)
export function readingFocusForPath(path) {
  return Object.keys(readingFocusPages).find(focus => readingFocusPages[focus].path === path.replace(/\/$/, ''))
}

const p = text => `<p class="m-0 text-sm leading-[1.85] text-fl-body">${text}</p>`
const h2 = text => `<h2 class="m-0 text-xl font-medium leading-relaxed">${text}</h2>`
export function readingFocusLandingHtml(focus) {
  const page = readingFocusPages[focus]
  return p(page.intro) + h2('この占いの仕組み') + p(page.mechanism) + h2('入力と結果の取り扱い') +
    p(focus === 'konki' ? '生年月日と性別を計算APIへ送り、この画面の表示中だけ使います。入力をURLやアクセス解析へ送信せず、この画面では保存しません。' : '二人の生年月日と性別、関係、出会った年を計算APIへ送ります。相手の情報は計算と結果の表示にだけ利用し、この画面では保存しません。入力をURLやアクセス解析へ送ることはありません。') +
    h2('よくある質問') + page.faqs.map(([question, answer]) => `<h3 class="m-0 text-base font-medium">${question}</h3>${p(answer)}`).join('') +
    h2('詳しい見方') + p(`<a class="underline" href="${page.guide}">${page.guideTitle}</a>で、結果を現実の状況に照らす方法を確認できます。`)
}

export function getArchetype(kanshi: string): string {
  if (!kanshi || kanshi.length < 2) return ''
  const stem = kanshi[0]
  const branch = kanshi[1]
  const element = STEM_ELEMENT[stem] ?? ''
  const juniUnsei = JUNI_UNSEI_TABLE[stem]?.[branch] ?? ''
  const archetypeInfo = JUNI_UNSEI_TO_ARCHETYPE[juniUnsei]
  const elementTone = ELEMENT_TONE[element] ?? ''
  if (!archetypeInfo) return ''
  const stemDetail = STEM_DETAIL[stem]
  const branchDetail = BRANCH_DETAIL[branch]
  const stemPart = stemDetail ? ` 天干（${stem}）本質：${stemDetail.essence}才能：${stemDetail.talent}。弱点：${stemDetail.weakness}。` : ''
  const branchPart = branchDetail ? ` 地支（${branch}）本質：${branchDetail.essence}才能：${branchDetail.talent}。弱点：${branchDetail.weakness}。` : ''
  return `日柱アーキタイプ（${archetypeInfo.group}・${element}）：${archetypeInfo.core}。気質トーン：${elementTone}。十二運星：${juniUnsei}。${stemPart}${branchPart}`
}


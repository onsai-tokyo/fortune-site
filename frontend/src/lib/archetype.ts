// 日柱干支から動物占いデータを取得（十二運星ベース）
export function getAnimalFortune(kanshi: string): string {
  if (!kanshi || kanshi.length < 2) return ''
  const stem = kanshi[0]
  const branch = kanshi[1]
  const juniUnsei = JUNI_UNSEI_TABLE[stem]?.[branch]
  if (!juniUnsei) return ''
  const animalName = JUNI_UNSEI_TO_ANIMAL[juniUnsei]
  if (!animalName) return ''
  const data = ANIMAL_FORTUNE_DATA[animalName]
  if (!data) return ''
  const color = STEM_TO_COLOR[stem] ?? ''
  const colorNote = color && data.color[color] ? `【${color}の特性】${data.color[color]}` : ''
  return `動物占い（${animalName}・${color}）十二運星：${juniUnsei}：${data.base}${colorNote ? ' ' + colorNote : ''} 強み：${data.strengths} 弱み：${data.weaknesses} 恋愛：${data.love} 適職：${data.career}`
}

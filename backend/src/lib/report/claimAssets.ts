export function assetsByChapter(): Record<string, number> {
  return CLAIM_ASSETS.reduce<Record<string, number>>((acc, asset) => {
    acc[asset.chapter] = (acc[asset.chapter] ?? 0) + 1
    return acc
  }, {})
}

/** 章ごとに shape が何種類そろっているか。8章すべてで 8 になること */
export function shapeSpreadByChapter(): Record<string, number> {
  const seen = new Map<string, Set<string>>()
  for (const asset of CLAIM_ASSETS) {
    const set = seen.get(asset.chapter) ?? new Set<string>()
    set.add(asset.shape)
    seen.set(asset.chapter, set)
  }
  return Object.fromEntries([...seen].map(([chapter, set]) => [chapter, set.size]))
}

/** typeLabel の重複。章タイトルがかぶるので 0 であること */
export function duplicateTypeLabels(): string[] {
  const count = new Map<string, number>()
  for (const asset of CLAIM_ASSETS) {
    count.set(asset.typeLabel, (count.get(asset.typeLabel) ?? 0) + 1)
  }
  return [...count].filter(([, n]) => n > 1).map(([label]) => label)
}
